import { pluralize } from './format';

// Відмінювання одиниць продажу: 1 каністра, 3 каністри, 10 каністр
const FORMS = {
  каністра: ['каністра', 'каністри', 'каністр'],
  мішок: ['мішок', 'мішки', 'мішків'],
  флакон: ['флакон', 'флакони', 'флаконів'],
  пакет: ['пакет', 'пакети', 'пакетів'],
  'біг-бег': ['біг-бег', 'біг-беги', 'біг-бегів'],
};

export function qty(n, unit) {
  const forms = FORMS[unit];
  return `${n} ${forms ? pluralize(n, ...forms) : unit}`;
}
